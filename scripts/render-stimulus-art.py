"""Regenerate tiny Word-compatible PNGs from authored SVGs, entirely locally.
Requires Python Playwright and Chromium; no external image service or runtime build.
"""
from pathlib import Path
import json
from playwright.sync_api import sync_playwright
root=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
    page=browser.new_page()
    page.add_script_tag(path=str(root/'js/stimulus-art.js'))
    images=page.evaluate("""async()=>{
      const images={};
      for(const key of StimulusArt.keys){
        const url=URL.createObjectURL(new Blob([StimulusArt.svg(key)],{type:'image/svg+xml'}));
        const image=new Image();image.src=url;await image.decode();
        const canvas=document.createElement('canvas');canvas.width=canvas.height=96;
        canvas.getContext('2d').drawImage(image,0,0,96,96);
        images[key]=canvas.toDataURL('image/png').split(',')[1];URL.revokeObjectURL(url);
      }
      return images;
    }""")
    browser.close()
target=root/'js/stimulus-art-png.js'
target.write_text('// Generated by scripts/render-stimulus-art.py. Same vectors as the screen.\n(function(root){const images='+json.dumps(images,separators=(',',':'))+';root.StimulusArtPNG=images;if(typeof module!=="undefined")module.exports=images;})(typeof window==="undefined"?globalThis:window);\n')
print(f'{len(images)} icons, {target.stat().st_size} bytes')
